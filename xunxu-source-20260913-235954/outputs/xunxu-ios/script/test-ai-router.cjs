function setup(queue, options={}) {
  const calls=[];
  const service = new AILogicRouter({apiKey:'test-only-placeholder',endpoints:endpoint,...options,
    fetchImpl: async (url,init) => {
      calls.push({url,body:JSON.parse(init.body)});
      assert.equal(init.headers.Authorization, 'Bearer test-only-placeholder');
      assert.equal(url,'https://ark.cn-beijing.volces.com/api/v3/chat/completions');
      const next=queue.shift();
      if (next instanceof Response) return next;
      if (next instanceof Error) throw next;
      assert.notEqual(next,undefined,'unexpected extra model call');
      return Response.json({choices:[{finish_reason:'stop',message:{content:JSON.stringify(next)}}]});
    },
  });
  return {service,calls};
}
