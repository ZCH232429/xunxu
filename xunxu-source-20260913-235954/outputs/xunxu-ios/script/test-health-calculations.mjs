import assert from 'node:assert/strict';
import {heartZone,sleepHours,energyBalance,unionMilliseconds,localDay} from '../lib/health/calculations.js';
import {mergeHealthSummary} from '../lib/health/records.js';
import {healthRows} from '../lib/validation.js';
const start=new Date('2026-09-13T00:00:00Z'),end=new Date('2026-09-14T00:00:00Z');
const hr=(second,quantity,source='watch')=>({startDate:new Date(+start+second*1000),quantity,source});
assert.deepEqual(heartZone([hr(0,125),hr(30,125),hr(60,125)],20,start,end),{minutes:1,coverageMinutes:1,zone:[120,140],hasData:true});
assert.equal(heartZone([hr(0,125),hr(3600,125)],20,start,end).minutes,0,'No extrapolation over sparse samples');
assert.equal(heartZone([hr(0,125)],20,start,end).coverageMinutes,0,'A point is not a minute');
assert.equal(heartZone([hr(0,100),hr(60,160),hr(120,100),hr(180,160)],20,start,end).minutes,1,'Threshold crossing is interpolated');
assert.equal(heartZone([hr(0,125),hr(60,125),hr(0,125,'phone'),hr(60,125,'phone')],20,start,end).minutes,1,'Overlapping sources never double duration');
assert.equal(heartZone([hr(0,125),hr(60,125,'phone')],20,start,end).minutes,0,'Different sources are not stitched');
assert.equal(heartZone([hr(-60,125),hr(0,125)],20,start,end).minutes,0,'Outside-day samples ignored');
assert.throws(()=>heartZone([],0,start,end));
assert.equal(unionMilliseconds([[0,5],[2,8],[8,10],[20,19]]),10);
const sample=(a,b,value)=>({startDate:new Date(+start+a*3600000),endDate:new Date(+start+b*3600000),value});
const sleep=[sample(-1,1,3),sample(0,1,3),sample(1,2,4),sample(2,3,5),sample(3,4,2)];
assert.equal(sleepHours(sleep,start,end),2,'Core and deep only, clipped and deduplicated');
assert.equal(sleepHours(sleep,start,end,[1,3,4,5]),3,'Total sleep includes REM, not awake');
assert.equal(sleepHours([sample(2,3,5)],start,end),null,'No stages is missing, not zero');
assert.deepEqual(energyBalance(1600,400,1800,400),{calorieDeficit:200,ringProgress:.5});
assert.deepEqual(energyBalance(1600,0,2000,400),{calorieDeficit:-400,ringProgress:0});
assert.equal(energyBalance(1600,600,1000,400).ringProgress,1);
assert.equal(energyBalance(1600,600,1000,0).ringProgress,0);
const day=localDay(new Date(2026,8,13,9));
assert.equal(day.date,'2026-09-13');assert.equal(day.start.getHours(),0);assert.equal(day.sleepStart.getDate(),12);assert.equal(day.sleepEnd.getHours(),9);
assert.equal(localDay(new Date(2026,8,13,17)).sleepEnd.getHours(),12);
console.log('PASS: HealthKit zone coverage, source deduplication, sleep stages, energy math, local day boundaries.');
const existing=[{date:'2026-09-12',steps:123},{date:'2026-09-13',rhr:60,sleep:8,steps:500}];
const summary={date:'2026-09-13',updatedAt:end.toISOString(),activeEnergy:100,steps:1000,restingHeartRate:null,totalSleepDuration:7.4,sleepDuration:5.2,fatBurnZoneMinutes:20,available:{activeEnergy:true,sleep:true,heartRate:true}};
const merged=mergeHealthSummary(existing,summary);
assert.equal(merged.length,2);assert.equal(existing[1].steps,500,'Input not mutated');
assert.equal(merged[1].rhr,60,'Missing RHR must not erase manual record');
assert.equal(merged[1].sleep,7.4,'Recovery receives total sleep, not core+deep');
assert.equal(merged[1].coreDeepSleepHours,5.2);assert.equal(merged[1].energyComplete,false);
assert.equal(mergeHealthSummary(merged,summary).length,2,'Repeated import never adds duplicates');
assert.doesNotThrow(()=>healthRows(merged));
assert.throws(()=>mergeHealthSummary([],{...summary,available:{},steps:null,restingHeartRate:null,totalSleepDuration:null}));
console.log('PASS: health record merge preserves unavailable data and other dates; valid legacy cloud shape.');
const {dateKey,shift}=await import('../public/workbench/engine.js');
const previousTimezone=process.env.TZ;
try{
  process.env.TZ='America/New_York';
  assert.equal(dateKey(new Date('2026-09-13T01:30:00Z')),'2026-09-12');
  assert.equal(shift('2026-03-08',1),'2026-03-09');
  process.env.TZ='Asia/Seoul';
  assert.equal(dateKey(new Date('2026-09-13T01:30:00Z')),'2026-09-13');
}finally{if(previousTimezone===undefined)delete process.env.TZ;else process.env.TZ=previousTimezone;}
console.log('PASS: mobile food and HealthKit local dates align across time zones and DST.');
