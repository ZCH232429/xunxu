import assert from 'node:assert/strict';
import {CategorizationEngine as C,MealMathSolver as S,fromLegacy,toLegacy,consumeMeal,validateFood} from '../lib/fridge/core.js';
import {checkedFood} from '../../fitness-workbench/food-resolver.mjs';
const food=(id,name,category,macrosPer100g,stockGrams=1000)=>({id,name,category,macrosPer100g,stockGrams});
const rice=food('rice','米饭','CARB',{calories:130,protein:2.5,carbs:28,fat:.3});
const chicken=food('chicken','鸡胸肉','PROTEIN',{calories:120,protein:23,carbs:0,fat:3});
const veg=food('veg','西兰花','VEG',{calories:34,protein:3,carbs:6,fat:.4});
assert.equal(C.categorize('西兰花',veg.macrosPer100g),'VEG');assert.equal(C.categorize('菠菜饼干',rice.macrosPer100g),'CARB');
assert.equal(C.categorize('坚果',{calories:600,protein:20,carbs:20,fat:50}),'FAT');
assert.equal(C.categorize('鸡胸肉',chicken.macrosPer100g),'PROTEIN');
const solution=S.solve([rice,chicken,veg],{targetCalories:500,targetProtein:30});
assert.ok(Math.abs(solution.totals.calories-500)<15);assert.ok(Math.abs(solution.totals.protein-30)<3);
assert.ok(solution.portions.every(p=>p.grams>0&&p.grams<=1000&&Number.isInteger(p.grams)));
const short=S.solve([{...chicken,stockGrams:10}],{targetCalories:500,targetProtein:30});assert.equal(short.portions[0].grams,10);assert.equal(short.closeToTarget,false);
assert.equal(S.solve([],{targetCalories:500,targetProtein:30}).portions.length,0);
assert.throws(()=>S.solve([rice],{targetCalories:-1,targetProtein:30}));
assert.throws(()=>validateFood({...rice,stockGrams:-1}));
assert.throws(()=>validateFood({...rice,macrosPer100g:{...rice.macrosPer100g,carbs:NaN}}));
const label=checkedFood({name:'全麦面包',kind:'label',serving:{grams:40,kcal:100,p:4,c:18,f:2}});
assert.equal(label.kcal,250);assert.equal(label.p,10);assert.equal(label.c,45);assert.equal(label.f,5);
assert.throws(()=>checkedFood({name:'标签',kind:'label',serving:{grams:0,kcal:100,p:4,c:18,f:2}}));
assert.deepEqual(fromLegacy(toLegacy(rice)).macrosPer100g,rice.macrosPer100g);
const state={foods:[rice,chicken,veg].map(toLegacy),meals:[],closedDays:['2026-09-13']};
const command={id:'meal-1',date:'2026-09-13',meal:'午餐',portions:solution.portions};
const consumed=consumeMeal(state,command);
assert.equal(state.meals.length,0);assert.equal(consumed.meals.length,1);assert.equal(consumed.closedDays.length,0);
for(const p of solution.portions)assert.equal(consumed.foods.find(f=>f.id===p.foodId).stockGrams,1000-p.grams);
assert.equal(consumeMeal(consumed,command),consumed,'Idempotent repeated consumption');
assert.throws(()=>consumeMeal(state,{...command,portions:[{foodId:'rice',grams:1001}]}));
assert.throws(()=>consumeMeal(state,{...command,portions:[{foodId:'rice',grams:10},{foodId:'rice',grams:10}]}));
assert.equal(state.foods[0].stockGrams,1000);
console.log('PASS: label serving normalization, macro-energy categorization, bounded solver, invalid targets, atomic/idempotent stock consumption.');
